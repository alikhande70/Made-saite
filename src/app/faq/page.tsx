export default function FaqPage() {
  /* FAQPage structured data — the answers below are the store's own policy text. */
  const jsonLd = {
    '@context': 'https://schema.org',
    '@type': 'FAQPage',
    url: `${siteUrl()}/faq`,
    mainEntity: FAQ.map((item) => ({
      '@type': 'Question',
      name: item.q,
      acceptedAnswer: { '@type': 'Answer', text: item.a },
    })),
  };

  return (
    <>
      <JsonLd data={jsonLd} />
      <StaticPage
        breadcrumb="پرسش‌های پرتکرار"
        title="پرسش‌های پرتکرار"
        intro="پاسخ پرسش‌های رایج دربارهٔ انتخاب قطعه، سفارش، پرداخت و ارسال."
        sections={FAQ.map((item) => ({ heading: item.q, paragraphs: [item.a] }))}
      />
    </>
  );
}
